import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ENABLE_URL =
  "https://raw.githubusercontent.com/brokensandals/wordlists/master/lists/enable1.txt";
const BLOCKLIST_URL =
  "https://raw.githubusercontent.com/brokensandals/wordlists/master/lists/ldnoobw.txt";

const MANUAL_ALLOWLIST = [];

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sharedOutputPath = path.join(rootDir, "shared", "generated", "dictionary-data.ts");
const functionOutputPath = path.join(
  rootDir,
  "supabase",
  "functions",
  "_shared",
  "generated",
  "dictionary-data.ts"
);

function normalizeWord(word) {
  return word.trim().toLowerCase();
}

function parseWordLines(text) {
  return text
    .split(/\r?\n/)
    .map((line) => normalizeWord(line))
    .filter((word) => /^[a-z]+$/.test(word));
}

function filterWords(words, blockedWords, allowedWords = []) {
  const blockedSet = new Set(parseWordLines(blockedWords).filter((word) => !allowedWords.includes(word)));
  return Array.from(new Set(parseWordLines(words))).filter((word) => !blockedSet.has(word));
}

function chunkWords(words, wordsPerLine = 18) {
  const lines = [];
  for (let index = 0; index < words.length; index += wordsPerLine) {
    lines.push(words.slice(index, index + wordsPerLine).join(" "));
  }
  return lines.join("\n");
}

function renderModule(words) {
  const body = chunkWords(words);
  return `/**
 * Generated by scripts/sync-enable-dictionary.mjs.
 * Source dictionary: ENABLE1 (Public Domain) via ${ENABLE_URL}
 * Filter list: LDNOOBW English list (CC BY 4.0) via ${BLOCKLIST_URL}
 * This build removes exact single-token blocklisted words while keeping the
 * base ENABLE word list for everything else.
 */
export const DICTIONARY_SOURCE = "ENABLE1 filtered with LDNOOBW exact-word removals";
export const DICTIONARY_WORD_COUNT = ${words.length};
export const DICTIONARY_WORDS_TEXT = \`
${body}
\`;
`;
}

async function downloadText(url) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Failed to download ${url}: ${response.status} ${response.statusText}`);
  }
  return response.text();
}

async function writeModule(filePath, contents) {
  await mkdir(path.dirname(filePath), { recursive: true });
  await writeFile(filePath, contents, "utf8");
}

async function main() {
  const [enableText, blocklistText] = await Promise.all([
    downloadText(ENABLE_URL),
    downloadText(BLOCKLIST_URL)
  ]);

  const filteredWords = filterWords(
    enableText,
    blocklistText,
    MANUAL_ALLOWLIST.map((word) => normalizeWord(word))
  );

  filteredWords.sort((left, right) => left.localeCompare(right));

  const moduleContents = renderModule(filteredWords);
  await Promise.all([
    writeModule(sharedOutputPath, moduleContents),
    writeModule(functionOutputPath, moduleContents)
  ]);

  console.log(`Wrote ${filteredWords.length} filtered ENABLE words.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
